/**
 * C3 — a data da sessão declarada na Configuração do certame aparece no Calendário Operacional como evento DERIVADO
 * (somente leitura): processo ativo, data válida, janela e sem duplicar evento cadastrado.
 */
import { readFileSync } from "fs";
import { join } from "path";
import { describe, expect, it } from "vitest";
import {
  CERTAME_SESSION_DATE_PATH, CERTAME_SESSION_SECTION, CERTAME_SESSION_TIME_PATH, deriveSessionEvents, sessionScheduleOf,
} from "../../domain/operationalCalendarSources";

const payload = (dataAbertura: unknown, horarioAbertura?: unknown) => ({ sections: { CERTAME_CONFIG: { dataAbertura, ...(horarioAbertura !== undefined ? { horarioAbertura } : {}) } } });
const proc = (id: string, processNumber = "12/2026", object = "Aquisição de materiais") => ({ id, processNumber, object });

describe("sessionScheduleOf", () => {
  it("lê data e horário válidos; horário inválido vira vazio", () => {
    expect(sessionScheduleOf(payload("2026-11-10", "09:30"))).toEqual({ date: "2026-11-10", time: "09:30" });
    expect(sessionScheduleOf(payload("2026-11-10", "9h"))).toEqual({ date: "2026-11-10", time: "" });
    expect(sessionScheduleOf(payload("2026-11-10"))).toEqual({ date: "2026-11-10", time: "" });
  });
  it("data ausente, inválida ou inexistente ⇒ null (nada presumido)", () => {
    for (const d of [undefined, "", "10/11/2026", "2026-02-30", 20261110]) expect(sessionScheduleOf(payload(d))).toBeNull();
    expect(sessionScheduleOf(null)).toBeNull();
    expect(sessionScheduleOf({ sections: {} })).toBeNull();
  });
});

describe("deriveSessionEvents", () => {
  const records = [
    { subjectId: "p1", payload: payload("2026-11-10", "09:30") },
    { subjectId: "p2", payload: payload("2026-12-01") },
    { subjectId: "p-inativo", payload: payload("2026-11-12") },
    { subjectId: "p3", payload: payload(undefined) },
  ];
  const activeProcesses = [proc("p1"), proc("p2", "", ""), proc("p3")];

  it("só processos ativos, com data, dentro da janela", () => {
    const ev = deriveSessionEvents({ records, activeProcesses, from: "2026-11-01", to: "2026-11-30", existing: [] });
    expect(ev).toEqual([{
      id: "certame:p1", eventType: "sessao_publica", title: "Sessão pública — Processo 12/2026 — Aquisição de materiais",
      eventDate: "2026-11-10", eventEndDate: "", eventTime: "09:30", referenceType: "procurement_process", referenceId: "p1",
      autoGenerated: true, alertOffsetDays: 0, declaredIn: "certame_config",
    }]);
    expect(deriveSessionEvents({ records, activeProcesses, from: "2026-11-01", existing: [] }).map((e) => e.referenceId)).toEqual(["p1", "p2"]);
  });

  it("evento cadastrado (sessão/certame) do mesmo processo e dia prevalece — sem duplicata", () => {
    const existing = [{ eventType: "sessao_publica", referenceId: "p1", eventDate: "2026-11-10" }];
    expect(deriveSessionEvents({ records, activeProcesses, existing }).map((e) => e.referenceId)).toEqual(["p2"]);
    const otherDay = [{ eventType: "certame", referenceId: "p1", eventDate: "2026-11-11" }];
    expect(deriveSessionEvents({ records, activeProcesses, existing: otherDay }).map((e) => e.referenceId)).toEqual(["p1", "p2"]);
    const otherType = [{ eventType: "reuniao", referenceId: "p1", eventDate: "2026-11-10" }];
    expect(deriveSessionEvents({ records, activeProcesses, existing: otherType }).map((e) => e.referenceId)).toEqual(["p1", "p2"]);
  });

  it("título sem número/objeto não inventa dados", () => {
    const [e] = deriveSessionEvents({ records: [records[1]], activeProcesses, existing: [] });
    expect(e.title).toBe("Sessão pública — Processo licitatório");
  });
});

describe("contrato com o catálogo do Edital", () => {
  it("o catálogo declara a sessão na seção/caminhos lidos pelo calendário", () => {
    const catalog = JSON.parse(readFileSync(join(__dirname, "../../domain/institutionalTemplates/models/edital-pregao-eletronico-bll/catalog.v2.json"), "utf8")) as { vars: Array<{ name: string; source: string; path: string }> };
    const byName = new Map(catalog.vars.map((v) => [v.name, v]));
    expect(byName.get("processo.dataAbertura")).toMatchObject({ source: CERTAME_SESSION_SECTION, path: CERTAME_SESSION_DATE_PATH });
    expect(byName.get("processo.horarioAbertura")).toMatchObject({ source: CERTAME_SESSION_SECTION, path: CERTAME_SESSION_TIME_PATH });
  });
});
