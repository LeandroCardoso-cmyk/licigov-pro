/**
 * C3 — Calendário Operacional: a DATA DA SESSÃO declarada na Configuração do certame (registro governado do processo,
 * `procurement.source_fields` → `sections.CERTAME_CONFIG`) aparece no calendário, sem cópia nem segundo preenchimento.
 * Puro (sem I/O): recebe os registros já decodificados (integridade verificada) e os processos ATIVOS; nada é gravado.
 *
 * Regras: só processo ativo da MESMA organização; só data válida (AAAA-MM-DD) dentro da janela; horário só se HH:mm;
 * evento operacional já cadastrado para o mesmo processo e dia (sessão/certame) prevalece — sem duplicata.
 */

/** Seção/caminhos do registro governado em que o catálogo do Edital declara a sessão (ver `catalog.v2.json`). */
export const CERTAME_SESSION_SECTION = "CERTAME_CONFIG";
export const CERTAME_SESSION_DATE_PATH = "dataAbertura";
export const CERTAME_SESSION_TIME_PATH = "horarioAbertura";

export const CERTAME_SESSION_EVENT_PREFIX = "certame:";

export interface ProcessRef { readonly id: string; readonly processNumber: string; readonly object: string }

export interface DerivedSessionEvent {
  readonly id: string;
  readonly eventType: "sessao_publica";
  readonly title: string;
  readonly eventDate: string;
  readonly eventEndDate: "";
  readonly eventTime: string;
  readonly referenceType: "procurement_process";
  readonly referenceId: string;
  readonly autoGenerated: true;
  readonly alertOffsetDays: 0;
  /** Origem do evento (a tela explica de onde veio a data). */
  readonly declaredIn: "certame_config";
}

const SESSION_TYPES = new Set(["sessao_publica", "certame"]);

function isValidIsoDate(s: unknown): s is string {
  if (typeof s !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const d = new Date(`${s}T00:00:00Z`);
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s;
}

const isValidTime = (s: unknown): s is string => typeof s === "string" && /^([01]\d|2[0-3]):[0-5]\d$/.test(s);

/** Data/horário da sessão no payload decodificado do registro governado do processo (null = não declarada/ inválida). */
export function sessionScheduleOf(payload: unknown): { readonly date: string; readonly time: string } | null {
  const sections = (payload as { sections?: unknown } | null | undefined)?.sections;
  if (!sections || typeof sections !== "object") return null;
  const sec = (sections as Record<string, unknown>)[CERTAME_SESSION_SECTION];
  if (!sec || typeof sec !== "object") return null;
  const date = (sec as Record<string, unknown>)[CERTAME_SESSION_DATE_PATH];
  const time = (sec as Record<string, unknown>)[CERTAME_SESSION_TIME_PATH];
  return isValidIsoDate(date) ? { date, time: isValidTime(time) ? time : "" } : null;
}

export function deriveSessionEvents(input: {
  readonly records: readonly { readonly subjectId: string; readonly payload: unknown }[];
  readonly activeProcesses: readonly ProcessRef[];
  readonly from?: string;
  readonly to?: string;
  readonly existing: readonly { readonly eventType: string; readonly referenceId: string | null; readonly eventDate: string }[];
}): DerivedSessionEvent[] {
  const processes = new Map(input.activeProcesses.map((p) => [p.id, p] as const));
  const taken = new Set(input.existing.filter((e) => SESSION_TYPES.has(e.eventType) && e.referenceId).map((e) => `${e.referenceId}|${e.eventDate}`));
  const out: DerivedSessionEvent[] = [];
  for (const r of input.records) {
    const p = processes.get(r.subjectId);
    if (!p) continue;
    const s = sessionScheduleOf(r.payload);
    if (!s) continue;
    if ((input.from && s.date < input.from) || (input.to && s.date > input.to)) continue;
    if (taken.has(`${p.id}|${s.date}`)) continue;
    taken.add(`${p.id}|${s.date}`);
    const label = p.processNumber ? `Processo ${p.processNumber}` : "Processo licitatório";
    const object = p.object.trim();
    out.push({
      id: `${CERTAME_SESSION_EVENT_PREFIX}${p.id}`, eventType: "sessao_publica",
      title: `Sessão pública — ${label}${object ? ` — ${object.length > 120 ? `${object.slice(0, 117)}…` : object}` : ""}`,
      eventDate: s.date, eventEndDate: "", eventTime: s.time,
      referenceType: "procurement_process", referenceId: p.id, autoGenerated: true, alertOffsetDays: 0, declaredIn: "certame_config",
    });
  }
  return out;
}
